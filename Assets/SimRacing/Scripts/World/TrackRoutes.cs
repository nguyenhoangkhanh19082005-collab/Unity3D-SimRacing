        // tarmac radius 125..140 m. Clockwise seen from above, starting just behind the start lights at x = -16.
        public const float OvalStraightHalfLength = 150f, OvalTurnRadius = 132.5f, OvalCenterZ = -160.5f, OvalStartX = -19f, OvalSpacing = 2.5f;

        public static readonly Vector3[] CartoonOval = BuildOval();

        static Vector3[] BuildOval()
        {
            float straight = OvalStraightHalfLength * 2f, arc = Mathf.PI * OvalTurnRadius;
            float length = 2f * (straight + arc);
            int count = Mathf.RoundToInt(length / OvalSpacing);
            var points = new Vector3[count];
            float startOffset = OvalStartX + OvalStraightHalfLength;
            for (int i = 0; i < count; i++)
            {
                float s = (startOffset + i * length / count) % length;
                float x, z;
                if (s < straight) { x = -OvalStraightHalfLength + s; z = OvalCenterZ + OvalTurnRadius; }
                else if ((s -= straight) < arc) { float a = s / OvalTurnRadius; x = OvalStraightHalfLength + Mathf.Sin(a) * OvalTurnRadius; z = OvalCenterZ + Mathf.Cos(a) * OvalTurnRadius; }
                else if ((s -= arc) < straight) { x = OvalStraightHalfLength - s; z = OvalCenterZ - OvalTurnRadius; }
                else { s -= straight; float a = s / OvalTurnRadius; x = -OvalStraightHalfLength - Mathf.Sin(a) * OvalTurnRadius; z = OvalCenterZ - Mathf.Cos(a) * OvalTurnRadius; }
                points[i] = new Vector3(x, 0f, z);
            }
            return points;
        }
